// 自主记忆每层学习频率的出厂值与夹取范围 —— 单一真相。
//
// 为什么单独一个叶子模块：默认值同时被配置归一化（config.ts）与门禁（gates.ts）读取；
// 写在任一模块里都会让另一个反向依赖，且改默认值要改两处。
//
// 条数本身没有总上限：记忆多了只影响注入预算，不拒绝写入。这里限制的是**产生速度** ——
// 每层在窗口内最多新增多少条，防止 agent 在一轮里刷屏。合并 / 更新已有条目不占名额。

/** 每层在 10 分钟内最多新增多少条自主记忆。 */
export const NOTE_RATE_DEFAULTS = {
  global: 5,
  workspace: 5,
} as const

/** 频率窗口：10 分钟。界面文案与这里必须同步（改窗口要同时改词典里的「10 分钟」）。 */
export const NOTE_RATE_WINDOW_MS = 10 * 60_000

/** 下限：至少允许 1 条，0 会让这一层永远学不进来。 */
export const NOTE_RATE_MIN = 1
/** 上限：10 分钟 100 条已经远超正常对话节奏，再大等于关掉频率门。 */
export const NOTE_RATE_MAX = 100
